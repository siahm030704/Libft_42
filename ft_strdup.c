#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	len;
	char	*dup;

	len = ft_strlen(s) + 1;
	dup = malloc(len);
	if (dup == NULL)
	{
		return (NULL);
	}
	ft_strlcpy(dup, s, len);
	return (dup);
}
